import assert from 'node:assert/strict'
import test from 'node:test'
import { randomUUID } from 'node:crypto'

test('Circle activity reports only its rewarded tasks, all quests, and validates five-character flair', { skip: process.env.USE_FIREBASE_EMULATORS !== 'true' }, async () => {
    const { db } = await import('../../lib/firebaseAdmin.js')
    const { setTaskStatus } = await import('../tasks/taskStatusService.js')
    const { circleActivity, editCircleIdentity } = await import('./circleApi.js')
    const uid = `circle_activity_test_${randomUUID()}`
    const circleRef = db.collection('circles').doc(uid)
    const userRef = db.collection('users').doc(uid)
    const otherCircleRef = db.collection('circles').doc(`${uid}_other`)
    const personalTaskRef = db.collection('tasks').doc(`${uid}_personal`)
    const taskRefs = Array.from({ length: 6 }, (_, i) => db.collection('tasks').doc(`${uid}_${i}`))
    try {
        await userRef.set({ primaryCircleId: uid, progress: { xp: 0, level: 1, timeZone: 'UTC' } })
        await circleRef.set({ createdByUserId: uid, profile: { title: 'Study team', flair: '', banner: { bgColor: '#ffffff88', iconColor: '#334455', iconIndex: 0 } } })
        await circleRef.collection('members').doc(uid).set({ role: 'owner' })
        await otherCircleRef.set({ createdByUserId: uid })
        await otherCircleRef.collection('members').doc(uid).set({ role: 'owner' })
        await db.collection('questBoards').doc(uid).set({ userId: uid, questIds: ['tasks-1', 'win-1', 'hearts-1'], progress: {}, completed: {} })
        await Promise.all(taskRefs.map(ref => ref.set({ userId: uid, title: { segments: [{ rawText: 'Review algebra' }] }, circleId: uid, parentTaskId: null, status: 'Incomplete' })))
        assert.equal((await circleActivity(uid, uid)).events.length, 0, 'creating tasks does not count as completing them')
        await setTaskStatus({ userId: uid, taskId: taskRefs[0].id, status: 'In Progress' })
        assert.equal((await circleActivity(uid, uid)).events.length, 0)
        await personalTaskRef.set({ userId: uid, title: 'Private study task', parentTaskId: null, status: 'Incomplete' })
        await setTaskStatus({ userId: uid, taskId: personalTaskRef.id, status: 'Completed' })
        const personalBoard = await circleActivity(uid, uid)
        assert.equal(personalBoard.events.filter(event => event.type === 'task').length, 0)
        assert.equal(personalBoard.events.filter(event => event.type === 'quest').length, 1, 'quests from personal tasks still appear')
        await setTaskStatus({ userId: uid, taskId: taskRefs[0].id, status: 'Completed' })
        await setTaskStatus({ userId: uid, taskId: taskRefs[0].id, status: 'Incomplete' })
        await setTaskStatus({ userId: uid, taskId: taskRefs[0].id, status: 'Completed' })
        for (const ref of taskRefs.slice(1)) await setTaskStatus({ userId: uid, taskId: ref.id, status: 'Completed' })
        await circleRef.collection('activity').doc('legacy_personal').set({ type: 'task', userId: uid, xp: 5, description: 'Private study task', createdAt: new Date() })
        const board = await circleActivity(uid, uid)
        const taskEvents = board.events.filter(event => event.type === 'task')
        assert.equal(taskEvents.length, 4, 'only rewarded Circle tasks appear, without repeats or legacy personal entries')
        assert.ok(taskEvents.every(event => event.xp > 0 && event.description === 'Review algebra'))
        assert.ok(taskEvents.every(event => event.circleId === uid))
        const otherBoard = await circleActivity(uid, otherCircleRef.id)
        assert.equal(otherBoard.events.filter(event => event.type === 'task').length, 0, 'tasks are not broadcast to other Circles')
        assert.equal(otherBoard.events.filter(event => event.type === 'quest').length, 1, 'quests are broadcast to every joined Circle')
        assert.equal(board.events.find(event => event.type === 'quest').description, 'Complete 1 task')
        assert.equal(board.count, 5, 'four rewarded Circle tasks and one quest advance the goal')
        assert.equal(otherBoard.count, 5, 'contributions reach every joined Circle')
        await editCircleIdentity(uid, uid, { flair: 'STUDY' })
        await assert.rejects(editCircleIdentity(uid, uid, { flair: 'STUDYS' }), /up to 5/)
        await assert.rejects(editCircleIdentity(uid, uid, { flair: 'fuck' }), /appropriate/)
        await editCircleIdentity(uid, uid, { flair: '' })
    } finally {
        await db.recursiveDelete(circleRef)
        await db.recursiveDelete(otherCircleRef)
        await personalTaskRef.delete()
        await db.recursiveDelete(userRef)
        await Promise.all(taskRefs.map(ref => ref.delete()))
        await Promise.all(['wallets', 'questBoards', 'userStats'].map(collection => db.recursiveDelete(db.collection(collection).doc(uid))))
        for (const collection of ['taskRewardDays', 'rewardEvents']) {
            const docs = await db.collection(collection).where('userId', '==', uid).get()
            await Promise.all(docs.docs.map(doc => doc.ref.delete()))
        }
    }
})

test('Grand Quest repeats without a calendar reset and claims remain independent and idempotent', { skip: process.env.USE_FIREBASE_EMULATORS !== 'true' }, async () => {
    const { db } = await import('../../lib/firebaseAdmin.js')
    const { readCircleContexts, contributeQuests } = await import('./circleGoals.js')
    const { circleActivity, claimCircleGrandQuest, setPrimaryCircle } = await import('./circleApi.js')
    const { grandQuestRound } = await import('./circlePolicy.js')
    const uid = `grand_quest_test_${randomUUID()}`, other = `${uid}_other`, late = `${uid}_late`, switcher = `${uid}_switcher`
    const ref = db.collection('circles').doc(uid)
    const first = grandQuestRound(uid, 1), second = grandQuestRound(uid, 2)
    const record = async (start, amount, dayKey) => {
        const { ensureMembershipIndex } = await import('./circleMemberships.js')
        await ensureMembershipIndex(uid)
        return db.runTransaction(async tx => {
        const completed = Array.from({ length: amount }, (_, i) => ({ id: `quest-${start + i}`, instanceId: `quest-${start + i}:0`, label: 'Complete a task' }))
        const contexts = await readCircleContexts(tx, [uid], { questInstances: completed.map(q=>({userId:uid,dayKey,instanceId:q.instanceId})) })
        contributeQuests(tx, contexts, { userId: uid, dayKey, completed })
        })
    }
    try {
        await ref.set({ createdByUserId: uid })
        for (const userId of [uid, other, late, switcher]) await db.collection('users').doc(userId).set({ primaryCircleId: uid, progress: { level: 1, xp: 0 } })
        await db.collection('users').doc(switcher).update({ primaryCircleId: null })
        for (const userId of [uid, other, switcher]) await ref.collection('members').doc(userId).set({ role: 'member' })
        await record(0, first.target - 1, '2026-10-11')
        assert.equal((await circleActivity(uid, uid)).count, first.target - 1)
        await record(first.target - 1, 1, '2026-10-19')
        assert.equal((await circleActivity(uid, uid)).canClaim, true, 'crossing a week boundary preserves progress')
        await setPrimaryCircle(switcher, uid)
        assert.equal((await circleActivity(switcher, uid)).canClaim, false)
        await assert.rejects(claimCircleGrandQuest(switcher, uid, 1), /not available/)
        await setPrimaryCircle(uid, null)
        await assert.rejects(claimCircleGrandQuest(uid, uid, 1), /not available/)
        await setPrimaryCircle(uid, ref.id)
        await ref.collection('members').doc(late).set({ role: 'member' })
        await assert.rejects(claimCircleGrandQuest(late, uid, 1), /not available/)
        const claims = await Promise.all(Array.from({ length: 12 }, () => claimCircleGrandQuest(uid, uid, 1)))
        assert.equal(claims.reduce((sum, claim) => sum + claim.reward.xp, 0), first.reward.xp)
        assert.equal(claims.reduce((sum, claim) => sum + claim.reward.lumen, 0), first.reward.lumen)
        assert.equal(claims.filter(claim => !claim.alreadyClaimed).length, 1, 'a rapid burst pays exactly once')
        assert.equal((await db.collection('wallets').doc(uid).get()).data().balance, first.reward.lumen, 'the persisted balance receives one payout')
        const { grantXp } = await import('../economy/progression.js')
        const expectedProgress = grantXp({ level: 1, xp: 0 }, first.reward.xp)
        const actualProgress = (await db.collection('users').doc(uid).get()).data().progress
        assert.equal(actualProgress.level, expectedProgress.level)
        assert.equal(actualProgress.xp, expectedProgress.xp, 'the persisted XP receives one payout')
        assert.equal((await circleActivity(uid, uid)).count, 0)
        await record(first.target, 3, '2026-10-19')
        assert.equal((await circleActivity(uid, uid)).count, 3)
        assert.equal((await circleActivity(other, uid)).count, first.target, 'an unclaimed round stays available')
        await record(first.target + 3, second.target - 3, '2026-10-26')
        await record(first.target + 3, second.target - 3, '2026-10-26')
        assert.equal((await ref.collection('goals').doc('grandQuest').get()).data().count, first.target + second.target, 'duplicate contributions do not advance another round')
        assert.equal((await circleActivity(uid, uid)).claimCycle, 2)
        assert.equal((await claimCircleGrandQuest(uid, uid, 1)).reward.xp, 0, 'retrying an old claim never claims a new round')
        assert.equal((await claimCircleGrandQuest(uid, uid, 2)).reward.xp, second.reward.xp)
        assert.equal((await circleActivity(uid, uid)).count, 0)
        assert.equal((await claimCircleGrandQuest(other, uid, 1)).reward.xp, first.reward.xp)
        assert.equal((await circleActivity(other, uid)).claimCycle, 2)
        assert.equal((await claimCircleGrandQuest(late, uid, 2)).reward.xp, second.reward.xp)
    } finally {
        await db.recursiveDelete(ref)
        for (const userId of [uid, other, late, switcher]) await Promise.all(['users', 'wallets', 'userStats'].map(collection => db.recursiveDelete(db.collection(collection).doc(userId))))
    }
})


test('Legacy completions cannot be claimed by switching primary and unfinished progress is preserved', { skip: process.env.USE_FIREBASE_EMULATORS !== 'true' }, async () => {
    const { db } = await import('../../lib/firebaseAdmin.js')
    const { circleActivity, claimCircleGrandQuest } = await import('./circleApi.js')
    const uid = `grand_legacy_${randomUUID()}`, ref = db.collection('circles').doc(uid)
    try {
        await ref.set({})
        await ref.collection('members').doc(uid).set({ role: 'member' })
        await db.collection('users').doc(uid).set({ primaryCircleId: uid, progress: { level: 1, xp: 0 } })
        await ref.collection('goals').doc('grandQuest').set({ count: 13 })
        await ref.collection('grandQuestRounds').doc('1').set({ cycle: 1, eligible: [uid] })
        const board = await circleActivity(uid, uid)
        assert.equal(board.count, 3)
        assert.equal(board.claimCycle, null)
        assert.ok(board.target >= 50 && board.target <= 100)
        await assert.rejects(claimCircleGrandQuest(uid, uid, 1), /not available/)
    } finally {
        await db.recursiveDelete(ref)
        await db.collection('users').doc(uid).delete()
        await db.collection('wallets').doc(uid).delete()
    }
})
