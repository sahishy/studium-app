import test from 'node:test'
import assert from 'node:assert/strict'
import { Color, DoubleSide, Mesh, MeshStandardMaterial, SRGBColorSpace, Texture } from 'three'
import { createCrateCoreGlowMaterial, createCrateSurfaceMaterial, updateCrateCoreGlow } from './crateMaterials.js'

test('crate toon shading keeps the imported UV atlas and its color space', () => {
    const atlas = new Texture()
    atlas.colorSpace = SRGBColorSpace
    const original = new MeshStandardMaterial({ color: '#abcdef', map: atlas, side: DoubleSide })
    const material = createCrateSurfaceMaterial(original)
    assert.ok(material.isMeshToonMaterial)
    assert.equal(material.map, atlas)
    assert.equal(material.map.colorSpace, SRGBColorSpace)
    assert.ok(material.color.equals(original.color))
    assert.equal(material.side, DoubleSide)
    material.dispose()
    assert.equal(original.map, atlas, 'Does not dispose or replace the cached GLTF texture')
    original.dispose()
    atlas.dispose()
})

test('the core starts glowing white and smoothly uses the same emission material for rarity colors', () => {
    const atlas = new Texture()
    const original = new MeshStandardMaterial({ map: atlas, side: DoubleSide })
    const idleMaterial = createCrateSurfaceMaterial(original)
    const material = createCrateCoreGlowMaterial(original)
    const core = new Mesh(undefined, idleMaterial)
    assert.ok(material.isMeshStandardMaterial)
    assert.equal(material.toneMapped, false)
    assert.equal(material.side, DoubleSide)
    assert.ok(material.emissive.equals(new Color('#ffffff')))
    assert.equal(material.emissiveIntensity, 3)
    updateCrateCoreGlow(core, material, '#ffffff')
    assert.equal(core.material, material)
    updateCrateCoreGlow(core, material, '#22c55e')
    assert.equal(core.visible, true)
    assert.equal(core.material, material)
    assert.ok(material.emissive.equals(new Color('#22c55e')))
    assert.ok(material.emissiveIntensity > 1)
    assert.ok(material.color.equals(new Color('#000000')))
    const transitionColor = new Color('#22c55e').lerp(new Color('#a855f7'), 0.5)
    updateCrateCoreGlow(core, material, transitionColor, 4)
    assert.ok(material.emissive.equals(transitionColor))
    assert.equal(material.emissiveIntensity, 4)
    updateCrateCoreGlow(core, material, '#ffffff')
    assert.equal(core.visible, true, 'Core remains present during idle')
    assert.equal(core.material, material, 'No dark-core swap between idle and opening')
    assert.equal(idleMaterial.map, atlas, 'Keeps the original atlas intact')
    assert.ok(material.emissive.equals(new Color('#ffffff')))
    assert.equal(material.emissiveIntensity, 3)
    material.dispose()
    idleMaterial.dispose()
    original.dispose()
    atlas.dispose()
})
